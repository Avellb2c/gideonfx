class TransportProfile(StrEnum):
    SFTP_SSH_SFTP = "SFTP_SSH_SFTP"
    SCP_SSH_SCP = "SCP_SSH_SCP"
    STDIN_SSH_SCP = "STDIN_SSH_SCP"
